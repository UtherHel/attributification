package dev.utherhel.attributification.selftest;

import java.nio.file.Path;
import net.minecraft.client.Minecraft;

/**
 * In-game self-test, client side (client-only class: never referenced from common code). Inert unless dev/modtest
 * starts the client with -Dattributification.selftest=&lt;out dir&gt; and -Dattributification.selftest.side=client.
 *
 * <ul>
 *   <li>boot: waits for the title screen, checks the mod is loaded and every client mixin applies, saves a screenshot
 *   (shots/title.png), runs {@link ClientScenarios#title} (screens reachable without a world), quits</li>
 *   <li>mp: the client was started with --quickPlayMultiplayer; once in the world it runs
 *   {@link ClientScenarios#client}, then waits for the server's director to end the session (or, with
 *   -Dattributification.selftest.serverMod=false, quits by itself)</li>
 * </ul>
 * Results: &lt;out&gt;/client.json. Driven from the client tick by the SelfTestClientMixin. Generated by
 * dev/modtest/sync.py; edit the template.
 */
public final class ClientSelfTest {
    private static final boolean ON = SelfTest.OUT != null && SelfTest.SIDE.equals("client");
    private static final boolean SERVER_MOD = !"false".equals(System.getProperty(SelfTest.ID + ".selftest.serverMod"));

    private enum State { BOOT, TITLE, JOIN, RUN, LEAVE, DONE }

    private static State state = State.BOOT;
    private static int ticks, stateTicks, connectTicks;
    private static Report report;
    private static Script<Minecraft> script;

    private ClientSelfTest() {
    }

    public static boolean active() {
        return ON;
    }

    /** False in the mp client_only case: the server doesn't have the mod (scenes check graceful behaviour then). */
    public static boolean serverMod() {
        return SERVER_MOD;
    }

    public static void onClientTick(Minecraft mc) {
        if (!ON || state == State.DONE) return;
        ticks++;
        stateTicks++;
        try {
            switch (state) {
                case BOOT -> {
                    if (SelfTest.MODE.equals("mp")) {
                        report = new Report("client");
                        go(State.JOIN);
                        return;
                    }
                    if (!ClientCompat.onTitleScreen(mc)) {
                        stateTicks = 0;
                        if (ticks > 20 * 300) fail(mc, "boot/title_screen", "no title screen within 300 s, screen: " + ClientCompat.screenName(mc));
                        return;
                    }
                    if (stateTicks < 40) return;
                    report = new Report("client");
                    report.record("boot/title_screen", true, "reached after " + ticks / 20 + " s");
                    SelfTest.boot(report);
                    shot(mc, "title");
                    script = new Script<>(report);
                    ClientScenarios.title(script);
                    go(State.TITLE);
                }
                case TITLE -> {
                    if (script.tick(mc)) finish(mc);
                    else if (ticks > SelfTest.LIMIT) fail(mc, "limit", "the title scenes did not finish within " + SelfTest.LIMIT / 20 + " s");
                }
                case JOIN -> {
                    if (mc.player == null || mc.level == null || !ClientCompat.inWorld(mc)) {
                        stateTicks = 0;
                        String screen = ClientCompat.screenName(mc);
                        connectTicks = ClientCompat.screen(mc) instanceof net.minecraft.client.gui.screens.ConnectScreen ? connectTicks + 1 : 0;
                        if (ClientCompat.screen(mc) instanceof net.minecraft.client.gui.screens.DisconnectedScreen)
                            fail(mc, "join", "disconnected while joining: " + screenText(mc));
                        else if (connectTicks > 20 * 90)
                            fail(mc, "join", "stuck connecting to the server for 90 s" + threadDump());
                        else if (ticks > 20 * 300)
                            fail(mc, "join", "not in the world within 300 s, screen: " + screen + screenText(mc));
                        return;
                    }
                    if (stateTicks < 60) return;
                    report.record("join", true, "in the world after " + ticks / 20 + " s");
                    SelfTest.boot(report);
                    shot(mc, "joined");
                    script = new Script<>(report);
                    ClientScenarios.client(script);
                    go(State.RUN);
                }
                case RUN -> {
                    if (script.tick(mc)) {
                        shot(mc, "end");
                        if (SERVER_MOD) {
                            // tells the server's director that the client scenes are done (same machine, same out dir)
                            java.nio.file.Files.createDirectories(Path.of(SelfTest.OUT));
                            java.nio.file.Files.writeString(Path.of(SelfTest.OUT, "client.done"), "done\n");
                            go(State.LEAVE);
                        } else {
                            finish(mc);
                        }
                    } else if (ticks > SelfTest.LIMIT) {
                        fail(mc, "limit", "the client scenes did not finish within " + SelfTest.LIMIT / 20 + " s");
                    }
                }
                case LEAVE -> {
                    if (mc.level == null) {
                        report.record("session_end", true, "the server ended the session");
                        finish(mc);
                    } else if (stateTicks > 20 * 300) {
                        fail(mc, "session_end", "the server did not end the session within 300 s");
                    }
                }
                default -> {
                }
            }
        } catch (Throwable t) {
            fail(mc, "driver", Report.describe(t));
        }
    }

    /** Saves a screenshot of the last frame to &lt;out&gt;/shots/&lt;name&gt;.png (not in a headless client: nothing is
     * rendered there). */
    public static void shot(Minecraft mc, String name) {
        if (Boolean.getBoolean("modtest.headless")) return;
        try {
            ClientCompat.screenshot(mc, Path.of(SelfTest.OUT, "shots", name + ".png"));
        } catch (Throwable t) {
            System.out.println("[ModTest] screenshot " + name + " failed: " + t);
        }
    }

    /** The texts a screen holds (a disconnect reason, a restart prompt), read reflectively: no screen API differs. */
    private static String screenText(Minecraft mc) {
        Object screen = ClientCompat.screen(mc);
        if (screen == null) return "";
        StringBuilder sb = new StringBuilder();
        for (Class<?> c = screen.getClass(); c != null && c != Object.class; c = c.getSuperclass()) {
            for (java.lang.reflect.Field f : c.getDeclaredFields()) {
                if (java.lang.reflect.Modifier.isStatic(f.getModifiers())) continue;
                try {
                    f.setAccessible(true);
                    Object v = f.get(screen);
                    if (v instanceof net.minecraft.network.chat.Component comp && !comp.getString().isBlank())
                        sb.append(sb.length() == 0 ? " [" : " | ").append(comp.getString());
                } catch (Throwable ignored) {
                    // inaccessible field: skip it
                }
            }
        }
        return sb.length() == 0 ? "" : sb.append("]").toString();
    }

    /** Writes every thread's stack to &lt;out&gt;/client-threads.txt and returns where the connect thread hangs. */
    private static String threadDump() {
        StringBuilder all = new StringBuilder(), connector = new StringBuilder();
        for (var e : Thread.getAllStackTraces().entrySet()) {
            String name = e.getKey().getName();
            all.append('"').append(name).append("\" ").append(e.getKey().getState()).append('\n');
            for (StackTraceElement el : e.getValue()) all.append("    at ").append(el).append('\n');
            if (name.startsWith("Server Connector") && connector.length() == 0) {
                StackTraceElement[] st = e.getValue();
                for (int i = 0; i < Math.min(6, st.length); i++) connector.append(i == 0 ? "" : " < ").append(st[i]);
            }
        }
        try {
            java.nio.file.Files.createDirectories(Path.of(SelfTest.OUT));
            java.nio.file.Files.writeString(Path.of(SelfTest.OUT, "client-threads.txt"), all.toString());
        } catch (Exception ignored) {
            // the dump is a diagnosis aid only
        }
        return connector.length() == 0 ? " (no connect thread; threads: out/client-threads.txt)"
                : "; the connect thread is at " + connector + " (all threads: out/client-threads.txt)";
    }

    private static void go(State s) {
        state = s;
        stateTicks = 0;
    }

    private static void fail(Minecraft mc, String name, String detail) {
        if (report == null) report = new Report("client");
        report.record(name, false, detail);
        finish(mc);
    }

    private static void finish(Minecraft mc) {
        state = State.DONE;
        report.write(SelfTest.OUT, SelfTest.MODE);
        mc.stop();
    }
}
