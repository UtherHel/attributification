package dev.utherhel.attributification.selftest;

import java.util.Arrays;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import net.minecraft.network.chat.Component;
import net.minecraft.server.MinecraftServer;
import net.minecraft.server.level.ServerPlayer;

/**
 * In-game self-test, dedicated-server side. Inert unless dev/modtest starts the server with
 * -Dattributification.selftest=&lt;out dir&gt; and -Dattributification.selftest.side=server (one boolean check per tick otherwise).
 *
 * <ul>
 *   <li>boot: once the server ticks, checks that the mod is loaded and every mixin of this side applies, then stops</li>
 *   <li>full: also runs {@link Scenarios#server} (no players), then stops</li>
 *   <li>mp: waits for -Dattributification.selftest.players=N players, runs {@link Scenarios#player}, waits until the modded
 *   client finished its own scenes (it writes &lt;out&gt;/client.done; -Dattributification.selftest.waitClient=false for a
 *   vanilla client), kicks the players, stops</li>
 * </ul>
 * Scenes work around block 0, 0 of the overworld: before they start, the chunks from -16, -16 to 15, 15 are
 * force-loaded, so entities summoned there stay loaded and tick without a player nearby (a server without players
 * keeps at most its spawn chunks, which on 1.21+ need not include 0, 0).
 * Results: &lt;out&gt;/server.json. Driven from the server tick by the SelfTestServerMixin. Generated by
 * dev/modtest/sync.py; edit the template.
 */
public final class SelfTest {
    public static final String ID = "attributification";
    static final String OUT = System.getProperty(ID + ".selftest");
    static final String MODE = System.getProperty(ID + ".selftest.mode", "boot");
    static final String SIDE = System.getProperty(ID + ".selftest.side", "server");
    static final int PLAYERS = Integer.getInteger(ID + ".selftest.players", 1);
    static final int LIMIT = Integer.getInteger(ID + ".selftest.limit", 20 * 600);
    static final boolean WAIT_CLIENT = !"false".equals(System.getProperty(ID + ".selftest.waitClient"));
    private static final Set<String> SCENES = new HashSet<>(Arrays.asList(
        System.getProperty(ID + ".selftest.scene", "all").split(",")));
    private static final boolean ON = OUT != null && SIDE.equals("server");

    private enum State { START, WAIT_PLAYERS, RUN, WAIT_CLIENT, DONE }

    private static State state = State.START;
    private static int ticks, waited, joinedTicks;
    private static Report report;
    private static Script<MinecraftServer> script;

    private SelfTest() {
    }

    public static boolean active() {
        return ON;
    }

    static boolean wants(String scene) {
        return SCENES.contains("all") || SCENES.contains(scene);
    }

    public static void onServerTick(MinecraftServer server) {
        if (!ON || state == State.DONE || !server.isDedicatedServer()) return;
        ticks++;
        try {
            switch (state) {
                case START -> {
                    if (ticks < 20) return;
                    report = new Report("server");
                    boot(report);
                    if (!MODE.equals("boot")) TestCompat.command(server, "forceload add -16 -16 15 15");
                    if (MODE.equals("full")) {
                        script = new Script<>(report);
                        script.waitTicks(20); // the force-loaded chunks load meanwhile
                        Scenarios.server(script);
                        state = State.RUN;
                    } else if (MODE.equals("mp")) {
                        state = State.WAIT_PLAYERS;
                    } else {
                        finish(server);
                    }
                }
                case WAIT_PLAYERS -> {
                    if (server.getPlayerList().getPlayerCount() < PLAYERS) {
                        joinedTicks = 0;
                        if (++waited > 20 * 240) {
                            report.record("players", false, "no player joined within 240 s");
                            finish(server);
                        }
                        return;
                    }
                    if (++joinedTicks < 60) return; // the client finishes loading the world meanwhile
                    report.record("players", true, server.getPlayerList().getPlayerCount() + " joined");
                    script = new Script<>(report);
                    Scenarios.player(script);
                    state = State.RUN;
                }
                case RUN -> {
                    if (script.tick(server)) {
                        if (MODE.equals("mp") && WAIT_CLIENT) {
                            waited = 0;
                            state = State.WAIT_CLIENT;
                        } else {
                            finish(server);
                        }
                    } else if (ticks > LIMIT) {
                        report.record("limit", false, "the scenes did not finish within " + LIMIT / 20 + " s (step "
                            + script.index() + "/" + script.size() + ")");
                        finish(server);
                    }
                }
                case WAIT_CLIENT -> {
                    if (java.nio.file.Files.exists(java.nio.file.Path.of(OUT, "client.done"))) {
                        finish(server);
                    } else if (server.getPlayerList().getPlayerCount() == 0) {
                        report.record("client_scenes", false, "the player left before the client finished its scenes");
                        finish(server);
                    } else if (++waited > 20 * 300) {
                        report.record("client_scenes", false, "the client did not finish its scenes within 300 s");
                        finish(server);
                    }
                }
                default -> {
                }
            }
        } catch (Throwable t) {
            if (report == null) report = new Report("server");
            report.record("driver", false, Report.describe(t));
            finish(server);
        }
    }

    static void boot(Report r) {
        boolean loaded = ModTestHook.isLoaded(ID);
        r.record("boot/mod_loaded", loaded, ModTestHook.loader() + " " + TestCompat.versionName() + ", " + ID + " "
            + ModTestHook.version(ID));
        String audit = ModTestHook.audit();
        r.record("boot/mixin_audit", audit == null, audit == null ? "every mixin of this side applied" : audit);
        for (String other : System.getProperty(ID + ".selftest.expect", "").split(",")) {
            if (other.isBlank()) continue;
            r.record("boot/loaded_" + other, ModTestHook.isLoaded(other), other + " " + ModTestHook.version(other));
        }
    }

    /** The first joined player (mp mode). */
    public static ServerPlayer player(MinecraftServer server) {
        List<ServerPlayer> ps = server.getPlayerList().getPlayers();
        if (ps.isEmpty()) throw new IllegalStateException("no player online");
        return ps.get(0);
    }

    private static void finish(MinecraftServer server) {
        state = State.DONE;
        report.write(OUT, MODE);
        for (ServerPlayer p : List.copyOf(server.getPlayerList().getPlayers())) {
            p.connection.disconnect(Component.literal("modtest done"));
        }
        server.halt(false);
    }
}
