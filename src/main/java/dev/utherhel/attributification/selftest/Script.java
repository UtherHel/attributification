package dev.utherhel.attributification.selftest;

import java.util.ArrayList;
import java.util.List;
import java.util.function.Consumer;
import java.util.function.Function;
import java.util.function.Predicate;

/**
 * A list of tick steps over a context (the {@code MinecraftServer} on the server, {@code Minecraft} on the client).
 * Each step returns true when it is done; a step that throws fails its scene, and the run goes on with the next scene.
 * Scenes are opened with {@link #scene(String)}, which returns false (and records nothing) when the scene filter
 * ({@code -D<modid>.selftest.scene=a,b}) leaves it out. Generated by dev/modtest/sync.py; edit the template.
 */
public final class Script<C> {
    public interface Step<C> {
        boolean tick(C ctx) throws Exception;
    }

    record Entry<C>(String scene, Step<C> step) {
    }

    final List<Entry<C>> steps = new ArrayList<>();
    private final Report report;
    private String scene = "setup";
    private int index;
    private String failedScene;

    Script(Report report) {
        this.report = report;
    }

    /** Starts a scene; false when the filter skips it (then add nothing for it). */
    public boolean scene(String name) {
        if (!SelfTest.wants(name)) return false;
        scene = name;
        return true;
    }

    public Script<C> run(Consumer<C> action) {
        steps.add(new Entry<>(scene, ctx -> {
            action.accept(ctx);
            return true;
        }));
        return this;
    }

    public Script<C> waitTicks(int n) {
        int[] left = {n};
        steps.add(new Entry<>(scene, ctx -> --left[0] <= 0));
        return this;
    }

    /** Runs {@code action} once a tick for {@code n} ticks. */
    public Script<C> each(int n, Consumer<C> action) {
        int[] left = {n};
        steps.add(new Entry<>(scene, ctx -> {
            action.accept(ctx);
            return --left[0] <= 0;
        }));
        return this;
    }

    /** Waits until {@code cond} holds; fails the scene after {@code timeout} ticks. */
    public Script<C> until(String what, int timeout, Predicate<C> cond) {
        int[] t = {0};
        steps.add(new Entry<>(scene, ctx -> {
            if (cond.test(ctx)) return true;
            if (++t[0] > timeout) throw new IllegalStateException("timed out after " + timeout + " ticks waiting for " + what);
            return false;
        }));
        return this;
    }

    /** A check: {@code check} returns null on success, else what went wrong. Recorded as "scene/name". */
    public Script<C> check(String name, Function<C, String> check) {
        String sc = scene;
        steps.add(new Entry<>(scene, ctx -> {
            String fail;
            try {
                fail = check.apply(ctx);
            } catch (Throwable t) {
                fail = "threw " + Report.describe(t);
            }
            report.record(sc + "/" + name, fail == null, fail == null ? "ok" : fail);
            return true;
        }));
        return this;
    }

    /** Like {@link #check} but retried every tick until it passes or {@code timeout} ticks pass (the last answer counts). */
    public Script<C> eventually(String name, int timeout, Function<C, String> check) {
        String sc = scene;
        int[] t = {0};
        steps.add(new Entry<>(scene, ctx -> {
            String fail;
            try {
                fail = check.apply(ctx);
            } catch (Throwable e) {
                fail = "threw " + Report.describe(e);
            }
            if (fail != null && ++t[0] <= timeout) return false;
            report.record(sc + "/" + name, fail == null, fail == null ? "ok after " + t[0] + " ticks" : fail);
            return true;
        }));
        return this;
    }

    /** Advances; true once every step is done. */
    boolean tick(C ctx) {
        while (index < steps.size()) {
            Entry<C> e = steps.get(index);
            if (e.scene().equals(failedScene)) {
                index++;
                continue;
            }
            boolean done;
            try {
                done = e.step().tick(ctx);
            } catch (Throwable t) {
                report.record(e.scene() + "/step " + index, false, Report.describe(t));
                failedScene = e.scene();
                index++;
                continue;
            }
            if (!done) return false;
            index++;
        }
        return true;
    }

    int size() {
        return steps.size();
    }

    int index() {
        return index;
    }
}
